"""
error_analysis.py
Error breakdown from results/val_predictions.csv -> results/ERROR_ANALYSIS.md.
Only reports counts and rates computed from the predictions.

Usage: python scripts/error_analysis.py [--model efficientnet_b0]
"""

import argparse
import json
import os
import sys
from collections import Counter

import pandas as pd

import _common as C


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default=None, help="variant name in val_predictions.csv (default: primary)")
    args = ap.parse_args()

    pred_path = os.path.join(C.RESULTS, "val_predictions.csv")
    if not os.path.exists(pred_path):
        sys.exit("results/val_predictions.csv not found. Run scripts/evaluate.py first.")
    with open(os.path.join(C.RESULTS, "val_metrics.json")) as f:
        primary = json.load(f)["primary_model"]
    model = args.model or primary

    df = pd.read_csv(pred_path)
    df = df[df.model == model].copy()
    if df.empty:
        sys.exit(f"no rows for model '{model}'")
    pcols = [f"p{k}" for k in range(5)]
    df["confidence"] = df[pcols].max(axis=1)
    df["diff"] = (df.y_pred - df.y_true).abs()
    err = df[df.y_true != df.y_pred]
    n, n_err = len(df), len(err)

    lines = [f"# Error analysis: {model}", "",
             f"Validation split, n = {n} images (this split was also used for early stopping and "
             f"temperature fitting). Generated by `scripts/error_analysis.py` from "
             f"`results/val_predictions.csv`.", "",
             f"- Errors: {n_err} of {n} ({n_err / n:.1%})",
             f"- Off by one grade: {(err['diff'] == 1).sum()} ({(err['diff'] == 1).sum() / n_err:.1%} of errors)",
             f"- Off by two or more grades: {(err['diff'] >= 2).sum()} "
             f"({(err['diff'] >= 2).sum() / n_err:.1%} of errors)", "",
             "## Per-grade recall", "", "| True grade | n | correct | recall |", "|---|---:|---:|---:|"]
    for g in range(5):
        sub = df[df.y_true == g]
        ok = int((sub.y_pred == g).sum())
        lines.append(f"| {g} | {len(sub)} | {ok} | {ok / len(sub):.3f} |")

    pairs = Counter(zip(err.y_true, err.y_pred))
    lines += ["", "## Most frequent confusions (true -> predicted)", "",
              "| True | Predicted | count | share of errors |", "|---|---|---:|---:|"]
    for (t, p), c in pairs.most_common(8):
        lines.append(f"| {t} | {p} | {c} | {c / n_err:.1%} |")

    top = err.sort_values("confidence", ascending=False).head(12)
    lines += ["", "## 12 highest-confidence wrong predictions", "",
              "| id | true | predicted | confidence |", "|---|---:|---:|---:|"]
    for _, r in top.iterrows():
        lines.append(f"| {r['id']} | {int(r.y_true)} | {int(r.y_pred)} | {r.confidence:.3f} |")

    out = os.path.join(C.RESULTS, "ERROR_ANALYSIS.md")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
